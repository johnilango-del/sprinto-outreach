// Shared by middleware (edge) and the login route (node). Uses Web Crypto, available in both.
export const AUTH_COOKIE = 'od_auth';

export async function tokenFor(password) {
  const data = new TextEncoder().encode(`outreach-desk:${password}`);
  const hash = await crypto.subtle.digest('SHA-256', data);
  return Array.from(new Uint8Array(hash))
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('');
}

export function safeEqual(a, b) {
  const x = String(a || '');
  const y = String(b || '');
  if (x.length !== y.length) return false;
  let diff = 0;
  for (let i = 0; i < x.length; i++) diff |= x.charCodeAt(i) ^ y.charCodeAt(i);
  return diff === 0;
}
